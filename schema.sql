create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text unique not null,
  password_hash text not null,
  display_name text,
  created_at timestamptz not null default now()
);

alter table public.users add column if not exists display_name text;

create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  symbol text not null,
  label text not null,
  rule_type text not null,
  threshold double precision,
  enabled boolean not null default true,
  last_sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists alerts_user_id_idx on public.alerts(user_id);
create index if not exists alerts_enabled_idx on public.alerts(enabled);

-- Le backend Streamlit utilise une Secret key Supabase côté serveur.
-- Ne jamais exposer cette clé dans le dépôt GitHub ou dans le navigateur.

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  parent_id bigint references public.posts(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  shared_symbol text,
  shared_label text,
  shared_price double precision,
  shared_trend integer,
  shared_risk integer,
  created_at timestamptz not null default now()
);

create table if not exists public.post_likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_parent_id_idx on public.posts(parent_id);
create index if not exists post_likes_post_id_idx on public.post_likes(post_id);
