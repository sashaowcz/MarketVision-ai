create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  parent_id bigint references public.posts(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  shared_symbol text,
  shared_label text,
  shared_price double precision,
  shared_trend integer,
  shared_risk integer,
  created_at timestamptz not null default now()
);

create table if not exists public.post_likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_parent_id_idx on public.posts(parent_id);
create index if not exists post_likes_post_id_idx on public.post_likes(post_id);


-- AngelVision 2.4: propositions de marchés sans texte libre.
create table if not exists public.market_proposals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  symbol text not null,
  label text not null,
  period text not null check (period in ('1d','1w','1mo','6mo','1y')),
  scope text not null default 'public' check (scope in ('public','friend')),
  target_user_id bigint references public.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.market_likes (
  proposal_id bigint not null references public.market_proposals(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (proposal_id,user_id)
);

create index if not exists market_proposals_created_at_idx on public.market_proposals(created_at desc);
create index if not exists market_proposals_target_idx on public.market_proposals(target_user_id);
create index if not exists market_likes_proposal_idx on public.market_likes(proposal_id);
